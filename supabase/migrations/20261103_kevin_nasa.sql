-- =====================================================================
-- APORTACIÓN KEVIN: versión PostgreSQL/Supabase del módulo NASA
-- Sólo la Edge Function usa estas tablas. RLS queda activo y sin políticas
-- públicas para que el navegador nunca acceda directamente a los datos.
-- =====================================================================

create table if not exists public.cache_api_nasa (
  clave text primary key,
  respuesta jsonb not null,
  consultado_en timestamptz not null default now(),
  expira_en timestamptz not null
);

create index if not exists idx_cache_api_nasa_expira
  on public.cache_api_nasa (expira_en);

create table if not exists public.objetos_nasa (
  id bigint generated by default as identity primary key,
  nasa_id text not null unique,
  nombre text not null,
  tipo text not null default 'asteroide'
    check (tipo in ('asteroide', 'cometa', 'otro')),
  magnitud_absoluta numeric(8,3),
  diametro_min_m numeric(18,2),
  diametro_max_m numeric(18,2),
  potencialmente_peligroso boolean not null default false,
  url_jpl text,
  datos_json jsonb,
  consultado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create index if not exists idx_objetos_nasa_peligroso
  on public.objetos_nasa (potencialmente_peligroso);

create table if not exists public.aproximaciones_nasa (
  id bigint generated by default as identity primary key,
  objeto_nasa_id bigint not null references public.objetos_nasa(id) on delete cascade,
  fecha_aproximacion timestamptz not null,
  cuerpo_orbitado text not null default 'Earth',
  velocidad_kmh numeric(18,2),
  distancia_km numeric(20,2),
  distancia_lunar numeric(18,6),
  datos_json jsonb,
  creado_en timestamptz not null default now(),
  unique (objeto_nasa_id, fecha_aproximacion, cuerpo_orbitado)
);

create index if not exists idx_aproximaciones_nasa_fecha
  on public.aproximaciones_nasa (fecha_aproximacion);

create table if not exists public.push_nasa (
  id bigint generated by default as identity primary key,
  endpoint_hash text not null unique,
  endpoint text not null,
  p256dh text not null,
  auth text not null,
  creado_en timestamptz not null default now(),
  ultimo_envio timestamptz
);

alter table public.cache_api_nasa enable row level security;
alter table public.objetos_nasa enable row level security;
alter table public.aproximaciones_nasa enable row level security;
alter table public.push_nasa enable row level security;

comment on table public.cache_api_nasa is 'Caché de servidor exclusiva del explorador NASA de Kevin.';
comment on table public.push_nasa is 'Suscripciones Web Push exclusivas del módulo NASA.';
