--
-- Una sola base con los módulos de todo el equipo:
--   · Común ............ grupos, usuarios, insignias, usuario_insignias, cache_api
--   · Videojuego (Miguel) misiones, articulos, preguntas, opciones, intentos,
--                        progreso, jefes_derrotados, push_juego
--   · Línea del tiempo (Rommel) etapas, eventos_linea_tiempo, vinetas,
--                        progreso_etapas, push_suscripciones
--   · Explorador NASA (Kevin) cache_api_nasa, objetos_nasa,
--                        aproximaciones_nasa, push_nasa
--   · Catálogo ......... objetos_espaciales
--
-- Traducida del MySQL del equipo (api/sql/*.sql) + la migración de Kevin
-- (20261103_kevin_nasa.sql). Se puede ejecutar más de una vez: usa
-- "if not exists" y "on conflict do nothing", así no choca con las tablas
-- NASA que Kevin ya creó en Supabase.
--
-- Notas de la traducción MySQL -> PostgreSQL:
--   · AUTO_INCREMENT            -> generated by default as identity
--   · ENUM(...)                 -> text + check
--   · tinyint(1) (activa, es_correcta, correcta) -> smallint 0/1, para que
--     las consultas del PHP como "activa = 1" o SUM(correcta) sigan igual.
--   · ON UPDATE CURRENT_TIMESTAMP -> trigger tocar_actualizado_en()
--   · json -> jsonb · timestamp/datetime -> timestamptz
--   · RLS activo en todas las tablas y sin políticas públicas: el navegador
--     nunca lee la base directo; solo el backend (PHP o Edge Functions).
--
-- Cómo subirla: pegar todo en Supabase > SQL Editor > Run,
-- o con la CLI:  supabase db push
-- =====================================================================

-- ---------------------------------------------------------------------
-- Utilidad: reemplazo de "ON UPDATE CURRENT_TIMESTAMP" de MySQL
-- ---------------------------------------------------------------------
create or replace function public.tocar_actualizado_en()
returns trigger language plpgsql as $$
begin
  new.actualizado_en := now();
  return new;
end $$;

